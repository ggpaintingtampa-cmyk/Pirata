/** Built-in Zod messages seen on the client, keyed by the English prefix Zod 4 emits. */
const ZOD_PREFIXES: [RegExp, string][] = [
  [/^Too small/, 'Demasiado corto'], [/^Too big/, 'Demasiado largo'], [/^Invalid input/, 'Valor inválido'], [/^Invalid option/, 'Opción inválida'], [/^Invalid email/, 'Correo inválido'], [/^Invalid UUID/, 'ID inválido'], [/^Expected/, 'Valor inválido'], [/^Unrecognized key/, 'Campo no reconocido'],
];
export function fieldMessage(locale: Locale, message: string): string {
  if (locale !== 'es') return message;
  const known = fieldStrings[message];
  if (known) return known;
  for (const [pattern, text] of ZOD_PREFIXES) if (pattern.test(message)) return text;
  return message;
}
